-- 7.1 验证角色创建
SELECT role_id, role_name, role_key, role_sort, data_scope, status, remark
FROM sys_role
WHERE role_id IN (200, 201, 202, 203, 104)
ORDER BY role_id;

-- 7.2 验证各角色权限数量
SELECT r.role_id, r.role_name, COUNT(rm.menu_id) as menu_count
FROM sys_role r
LEFT JOIN sys_role_menu rm ON r.role_id = rm.role_id
WHERE r.role_id IN (200, 201, 202, 203, 104)
GROUP BY r.role_id, r.role_name
ORDER BY r.role_id;

-- 7.3 验证工单流转权限分配
SELECT r.role_id, r.role_name,
       MAX(CASE WHEN m.perms = 'dms:workorder:dispatch' THEN '✅' ELSE '-' END) as '派工',
       MAX(CASE WHEN m.perms = 'dms:workorder:reassign' THEN '✅' ELSE '-' END) as '改派',
       MAX(CASE WHEN m.perms = 'dms:workorder:accept' THEN '✅' ELSE '-' END) as '接单',
       MAX(CASE WHEN m.perms = 'dms:workorder:process' THEN '✅' ELSE '-' END) as '处理',
       MAX(CASE WHEN m.perms = 'dms:workorder:complete' THEN '✅' ELSE '-' END) as '完工',
       MAX(CASE WHEN m.perms = 'dms:workorder:verify' THEN '✅' ELSE '-' END) as '验收',
       MAX(CASE WHEN m.perms = 'dms:workorder:reject' THEN '✅' ELSE '-' END) as '驳回',
       MAX(CASE WHEN m.perms = 'dms:workorder:cancel' THEN '✅' ELSE '-' END) as '撤销'
FROM sys_role r
LEFT JOIN sys_role_menu rm ON r.role_id = rm.role_id
LEFT JOIN sys_menu m ON rm.menu_id = m.menu_id
WHERE r.role_id IN (1, 200, 201, 202, 203, 104)
  AND (m.perms LIKE 'dms:workorder:%' OR m.menu_id IS NULL)
GROUP BY r.role_id, r.role_name
ORDER BY r.role_id;
