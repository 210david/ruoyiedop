-- ============ 4. 验证 ============
SELECT r.role_id, r.role_name, r.role_key, r.data_scope, COUNT(rm.menu_id) AS menu_count
FROM sys_role r
LEFT JOIN sys_role_menu rm ON r.role_id = rm.role_id
JOIN sys_menu m ON rm.menu_id = m.menu_id AND m.menu_id BETWEEN 4000 AND 4199
WHERE r.role_id IN (300, 301, 302, 303, 304, 104)
GROUP BY r.role_id, r.role_name, r.role_key, r.data_scope
ORDER BY r.role_id;
