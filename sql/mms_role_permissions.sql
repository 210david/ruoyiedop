SELECT '=== MMS角色权限创建完成 ===' AS result;

-- MMS专属角色验证
SELECT r.role_id, r.role_name, r.role_key, r.data_scope, r.remark,
       COUNT(rm.menu_id) AS menu_count
FROM sys_role r
LEFT JOIN sys_role_menu rm ON rm.role_id = r.role_id
WHERE r.role_id BETWEEN 600 AND 603
GROUP BY r.role_id, r.role_name, r.role_key, r.data_scope, r.remark
ORDER BY r.role_id;

-- 跨模块角色MMS权限验证
SELECT '=== 跨模块角色MMS权限验证 ===' AS result;
SELECT r.role_id, r.role_name, r.role_key,
       COUNT(rm.menu_id) AS mms_menu_count
FROM sys_role r
LEFT JOIN sys_role_menu rm ON rm.role_id = r.role_id
  AND rm.menu_id IN (SELECT menu_id FROM sys_menu WHERE perms LIKE 'mms:%' OR menu_id = 5000)
WHERE r.role_id IN (120, 121, 400, 401)
GROUP BY r.role_id, r.role_name, r.role_key
ORDER BY r.role_id;
