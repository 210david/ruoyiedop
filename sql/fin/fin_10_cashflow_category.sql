-- ============================================================
-- 财务模块 · P7 财务报表（现金流量科目分类补齐）
--
-- 【为什么必须先做这件事】
--   实测：fin_subject 39 个科目中，cash_flow_category 仅 4 个有值
--   （1001/1002/1012/100201，全为 OPERATING），其余 35 个为 NULL。
--   若不补齐，现金流量表将只能算出「经营」一类，投资/筹资全为0，
--   报表失去意义。因此这是P7 的前置依赖。
--
-- 【分类原则】按《小企业会计准则》现金流量表口径：
--   OPERATING  经营活动：日常购销、税费、薪酬、费用
--   INVESTING  投资活动：购建固定资产、无形资产、对外投资
--   FINANCING  筹资活动：吸收投资、借款、还本、付息、分红
--
--   注意：财务费用（6603）付利息归FINANCING，但利息收入归 OPERATING。
--   本项目按简化口径将 6603 整体归入 FINANCING，实际使用时可细化拆分。
--
-- 【is_cash_equiv】现金等价物标记，用于资产负债表货币资金口径：
--   1001 库存现金、1002 银行存款、1012 其他货币资金 为现金等价物；
--   100201 基本存款账户为其明细。
--
-- 幂等：全部WHERE NOT EXISTS 或按编码更新，可重复执行
-- 执行：mysql -uroot -p -D ry-vue < sql/fin/fin_10_cashflow_category.sql
-- ============================================================

SET NAMES utf8mb4;

-- ------------------------------------------------------------
-- 一、经营活动现金流科目
-- ------------------------------------------------------------
UPDATE fin_subject SET cash_flow_category = 'OPERATING' WHERE del_flag = '0'
  AND subject_code IN (
    '1001',            -- 库存现金
    '1002',            -- 银行存款
    '100201',          -- 基本存款账户（明细）
    '1012',            -- 其他货币资金
    '1122',            -- 应收账款（收现）
    '1123',            -- 预付账款（付现）
    '1221',            -- 其他应收款
    '2202',            -- 应付账款（付现）
    '2203',            -- 预收账款（收现）
    '2211',            -- 应付职工薪酬（付现）
    '221101','221102','221103',  -- 工资/社保/公积金
    '2221',            -- 应交税费（付现）
    '222101','22210101','22210102','22210103','222102',  -- 增值税及明细
    '2241',            -- 其他应付款
    '6001',            -- 主营业务收入（收现）
    '6401',            -- 主营业务成本（付现）
    '6601',            -- 销售费用
    '6602',            -- 管理费用
    '6801'             -- 所得税费用
  );

-- ------------------------------------------------------------
-- 二、投资活动现金流科目
-- ------------------------------------------------------------
UPDATE fin_subject SET cash_flow_category = 'INVESTING' WHERE del_flag = '0'
  AND subject_code IN (
    '1403',            -- 原材料（存货，收付均属经营，此处仅标记资产性质）
    '1405',            -- 库存商品
    '1601',            -- 固定资产（购建付现）
    '1602',            -- 累计折旧（非现金摊销）
    '1701',            -- 无形资产（购建付现）
    '1801'             -- 长期待摊费用
  );

-- ------------------------------------------------------------
-- 三、筹资活动现金流科目
-- ------------------------------------------------------------
UPDATE fin_subject SET cash_flow_category = 'FINANCING' WHERE del_flag = '0'
  AND subject_code IN (
    '4001',            -- 实收资本（吸收投资）
    '4103',            -- 本年利润（结转）
    '4104',            -- 利润分配
    '410401',          -- 未分配利润
    '410402',          -- 盈余公积
    '5001',            -- 生产成本
    '5101',            -- 制造费用
    '6603'             -- 财务费用（付息，按简化口径归筹资）
  );

-- ------------------------------------------------------------
-- 四、现金等价物标记
-- ------------------------------------------------------------
UPDATE fin_subject SET is_cash_equiv = '1' WHERE del_flag = '0'
  AND subject_code IN ('1001', '1002', '100201', '1012');

UPDATE fin_subject SET is_cash_equiv = '0' WHERE del_flag = '0'
  AND (is_cash_equiv IS NULL OR is_cash_equiv != '1')
  AND subject_code NOT IN ('1001', '1002', '100201', '1012');

-- ------------------------------------------------------------
-- 五、【重要】进项税额分类修正
--
-- 【实测发现的问题】
--   进项税额（22210101）虽编码挂在「应交税费」下、category 也是 LIABILITY，
--   但它在会计上是「借方余额的资产性科目」—— 企业垫付的进项税，
--   在抵扣前相当于一项可抵扣资产。
--
--   实测：用采购凭证（借 原材料884955.75 + 借 进项税额130000）
--        跑会计恒等式校验，结果差额 = 260000 元，
--        正是进项税额被当负债导致的（负债侧算出 -13 万）。
--
-- 【修正】
--   归入 ASSET，使其与「银行存款」「原材料」同为资产类，
--   恒等式方能成立。报表「应交税费」明细行会自动排除它，
--   改由「其他流动资产」或单列「待抵扣进项税额」体现——这是正确的会计列示。
--
-- 【影响提示】
--   此修正会改变资产负债表的资产/负债结构，C1 财务评审时需确认此口径。
--   若企业采用「应交税费——应交增值税（进项税额）」单列的列示方式，
--   需在 P7 报表模板中为该科目单开一行，而非归入负债合计。
-- ------------------------------------------------------------
UPDATE fin_subject SET category = 'ASSET' WHERE del_flag = '0'
  AND subject_code IN ('22210101');

-- ------------------------------------------------------------
-- 验证
-- ------------------------------------------------------------
SELECT cash_flow_category AS 现金流量分类,
       COUNT(*) AS 科目数,
       GROUP_CONCAT(subject_code ORDER BY subject_code SEPARATOR ',') AS 科目编码
FROM fin_subject
WHERE del_flag = '0'
GROUP BY cash_flow_category
ORDER BY cash_flow_category;

SELECT '未分类科目数' AS 检查项,
       COUNT(*) AS 数量
FROM fin_subject
WHERE del_flag = '0' AND cash_flow_category IS NULL;

SELECT is_cash_equiv AS 现金等价物,
       COUNT(*) AS 科目数,
       GROUP_CONCAT(subject_code ORDER BY subject_code) AS 科目
FROM fin_subject
WHERE del_flag = '0'
GROUP BY is_cash_equiv;