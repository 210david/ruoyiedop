SELECT r.role_id, r.role_name, r.role_key, r.data_scope, r.remark,
       COUNT(rm.menu_id) AS menu_count
FROM sys_role r
LEFT JOIN sys_role_menu rm ON rm.role_id = r.role_id
WHERE r.role_id BETWEEN 500 AND 505
GROUP BY r.role_id, r.role_name, r.role_key, r.data_scope, r.remark
ORDER BY r.role_id;
