SELECT r.role_id, r.role_name, r.role_key,
       COUNT(rm.menu_id) AS mms_menu_count
FROM sys_role r
LEFT JOIN sys_role_menu rm ON rm.role_id = r.role_id
  AND rm.menu_id IN (SELECT menu_id FROM sys_menu WHERE perms LIKE 'mms:%' OR menu_id = 5000)
WHERE r.role_id IN (100, 104, 120, 121, 122, 123, 124, 125, 126,
                    203, 400, 401, 402, 403, 404,
                    500, 501, 502,
                    600, 601, 602, 603)
  AND r.del_flag = '0'
GROUP BY r.role_id, r.role_name, r.role_key
ORDER BY r.role_id;
